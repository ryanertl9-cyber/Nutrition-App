// Writes sw.js: the service worker that makes Simply Nutrition installable and usable offline.
// The cache version is a hash of every precached file, so any change to the app produces a new
// version and phones pick it up (the app then offers "New version available").
// Run before publishing: node scripts/build-sw.mjs   (tests fail if sw.js is out of date)
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Everything the app needs to start with no network. URL -> file on disk.
export const PRECACHE = {
  '/': 'index.html',
  '/app/': 'app/index.html',
  '/privacy.html': 'privacy.html',
  '/terms.html': 'terms.html',
  '/src/core.js': 'src/core.js',
  '/src/sync.js': 'src/sync.js',
  '/src/app.js': 'src/app.js',
  '/src/config.js': 'src/config.js',
  '/src/vendor/supabase-2.119.0.js': 'src/vendor/supabase-2.119.0.js',
  '/src/vendor/zxing-library-0.23.0.min.js': 'src/vendor/zxing-library-0.23.0.min.js',
  '/data/foods.json': 'data/foods.json',
  '/assets/landing.js': 'assets/landing.js',
  '/manifest.webmanifest': 'manifest.webmanifest',
  '/favicon.svg': 'favicon.svg',
  '/apple-touch-icon.png': 'apple-touch-icon.png',
  '/assets/brand/favicon-32.png': 'assets/brand/favicon-32.png',
  '/assets/brand/icon-192.png': 'assets/brand/icon-192.png',
  '/assets/brand/icon-512.png': 'assets/brand/icon-512.png',
  '/assets/landing/scoreboard.webp': 'assets/landing/scoreboard.webp',
  '/assets/landing/gap.webp': 'assets/landing/gap.webp',
  '/assets/landing/map.webp': 'assets/landing/map.webp',
};

export function computeVersion() {
  const h = createHash('sha256');
  for (const [url, file] of Object.entries(PRECACHE)) { h.update(url); h.update(readFileSync(join(root, file))); }
  return h.digest('hex').slice(0, 12);
}

export function render(version) {
  return `// Generated by scripts/build-sw.mjs. Do not edit by hand.
// Simply Nutrition service worker: offline app shell and food data, versioned updates.
const VERSION = '${version}';
const CACHE = 'simply-nutrition-' + VERSION;
const PRECACHE = ${JSON.stringify(Object.keys(PRECACHE), null, 2)};

self.addEventListener('install', (event) => {
  // Download the whole new version before taking over, so the app never mixes old and new files.
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))));
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith('simply-nutrition-') && key !== CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

// The page asks the waiting version to take over when the person taps "Refresh".
self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  // Only this site's own files. Supabase, USDA and Google Fonts go straight to the network.
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    // Pages: serve the cached copy of /, /app/ etc. (works offline, opens instantly).
    const path = url.pathname.endsWith('/') ? url.pathname : url.pathname.replace(/index\\.html$/, '');
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match(path)) || (await cache.match(url.pathname)) || fetch(req).catch(() => cache.match('/app/'));
    })());
    return;
  }
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(url.pathname);
    return hit || fetch(req);
  })());
});
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const v = computeVersion();
  writeFileSync(join(root, 'sw.js'), render(v));
  console.log('Wrote sw.js, version', v);
}
